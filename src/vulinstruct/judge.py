"""CORRECT Lenient Stage 2 prompts and detector rationale preparation."""
import re
from html import unescape

JUDGE_PROTOCOL = "correct-lenient-stage2-v1"


def prepare_rationale(response):
    """Assemble Stage 1 reasoning from its assessment and analysis sections."""
    if not isinstance(response, str) or not response.strip():
        raise ValueError("Missing detector response for judging")
    assessment = re.search(r'<vulnerability_assessment>(.*?)</vulnerability_assessment>', response, re.S)
    if not assessment:
        return "V15 inherits V14 analysis (fallback parsing):\n\n" + response
    roots = re.findall(r'<suspected_root_cause>(.*?)</suspected_root_cause>', assessment.group(1), re.S)
    if len(roots) != 1 or not roots[0].strip():
        raise ValueError("Missing or ambiguous detector root-cause explanation")
    parts = ["V15 inherits V14 LLM knowledge scoring multi-layer analysis results:",
             "Suspected Root Cause: " + unescape(roots[0].strip())]
    start = response.lower().find("analysis process")
    end = response.lower().find("final conclusion", start) if start != -1 else -1
    if start != -1 and end != -1:
        parts.append("\nDetailed Analysis: " + response[start:end].strip())
    return "\n\n".join(parts)


